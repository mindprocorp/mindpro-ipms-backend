package kr.co.mindpro.ipms.domain.ai.skill;

import org.springframework.core.annotation.Order;
import org.springframework.stereotype.Component;

/**
 * 업무 등록 및 화면 이동 워크플로우 스킬.
 * 파일 업로드 → 분석 → 긍정 응답 → manageJobProgress 도구 호출 시나리오를 정의합니다.
 */
@Component
@Order(1)
public class BusinessWorkflowSkill implements AiSkill {

    @Override
    public String getName() {
        return "business-workflow";
    }

    @Override
    public String getContent() {
        return """
                # [Workflow Skill: Business Registration & UI Navigation]

                ## 1. 업무 목적
                파일 업로드 분석 후 사용자의 긍정 응답을 포착하여 `manageJobProgress` 도구를 **반드시 실제로 호출**하고, 그 반환값을 기준으로 결과를 안내합니다.

                ---

                ## 2. 핵심 시나리오: 파일 등록 확인 흐름

                ```
                [1] 사용자가 파일을 업로드함
                [2] 시스템이 파일을 분석하고 "진행사항에 등록해드릴까요?" 라고 제안함
                [3] 프론트엔드가 메시지에 내부 참조(임시 토큰, 시스템 시퀀스 등)를 포함시켜 전송함
                [4] 사용자가 "응", "해줘", "등록해줘" 등 긍정 응답을 보냄
                [5] AI는 내부 참조에서 파라미터를 추출하여 manageJobProgress를 즉시 호출함
                [6] 도구의 반환 문자열을 확인하고 성공/실패 결과를 사용자에게 안내함
                ```

                ---

                ## 3. 내부 참조(Internal Reference) 파싱 규칙

                사용자 메시지에 아래와 같은 내부 참조가 포함될 수 있습니다:

                ```
                (내부 참조: 현재 진행 중인 파일 토큰은 "xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx",
                 시스템 시퀀스는 "APPMST20260000515", 문서 번호는 "99"이다.
                 사용자가 긍정하면 이 정보를 사용하여 registerJobProgress를 호출해.)
                ```

                - `fileToken` → 내부 참조의 "파일 토큰" 값
                - `systemSeq` → 내부 참조의 "시스템 시퀀스" 값
                - `docSeq` → 내부 참조의 "문서 번호" 값
                - `officeSeq` → [접속자 정보]의 officeSeq 값
                - `userSeq` → [접속자 정보]의 사용자(loginUser) 값
                - `summary` → 이전 대화에서 분석된 파일 요약 내용

                ---

                ## 4. 긍정 응답 감지 및 즉시 실행 규칙

                ### 긍정으로 판단하는 표현
                "응", "어", "그래", "ㅇㅇ", "해줘", "등록해줘", "등록해", "부탁해", "진행해", "yes", "ok"

                ### 🚨 절대 금지 (위반 시 시스템 데이터 오염)
                - `manageJobProgress` 도구를 **실제로 호출하지 않고** 성공 응답 텍스트를 직접 생성하는 행위는 엄격히 금지됩니다.
                - 도구 호출 없이 "등록 성공", "시스템 반영 완료" 등의 문구를 출력하면 안 됩니다.
                - 내부 참조 값이 메시지에 있다고 해서 도구를 호출한 것으로 간주하지 마십시오.

                ### 실행 절차 (반드시 순서대로)
                1. 사용자의 긍정 응답을 감지한다.
                2. 메시지의 내부 참조에서 `fileToken`, `systemSeq`, `docSeq`를 추출한다.
                3. [접속자 정보]에서 `officeSeq`, `userSeq`를 가져온다.
                4. **`manageJobProgress` 도구를 즉시 호출한다.** (이 단계를 건너뛰는 것은 허용되지 않음)
                5. 도구의 반환값을 확인한다.
                6. 반환값에 따라 아래 응답 형식을 사용한다.

                ---

                ## 5. 도구 호출 파라미터 명세

                ```
                manageJobProgress(
                  actionType = "REGISTER",
                  systemSeq  = (내부 참조의 시스템 시퀀스),
                  fileToken  = (내부 참조의 파일 토큰),
                  summary    = (이전 대화에서 분석된 파일 요약),
                  docSeq     = (내부 참조의 문서 번호),
                  officeSeq  = (접속자 정보의 officeSeq),
                  userSeq    = (접속자 정보의 loginUser)
                )
                ```

                ---

                ## 6. 도구 반환값 해석 및 응답 형식

                ### 도구가 "작업결과: SUCCESS" 또는 "SUCCESS"를 포함하여 반환한 경우에만:

                > **사건 식별자 표시 우선순위** (사용자는 내부 시퀀스를 모릅니다):
                > 1. **출원번호(appNo)** — `40-2025-0219818` 형태의 실제 출원번호를 최우선 표시
                > 2. **관리번호(ourRef)** — 특허사무소 내부 관리번호(OurRef)를 함께 표시
                > 3. systemSeq(`APPMST...`, `CFTMST...` 등 내부 PK)는 절대 사용자에게 노출하지 마십시오.
                > RAG 컨텍스트 또는 히스토리에서 appNo, ourRef 값을 찾아 사용하십시오.

                ```markdown
                ### ✅ [업무 등록 성공 보고]
                ---
                📂 **대상 사건**: (출원번호 또는 사건번호, 예: 40-2025-0219818)
                📋 **관리번호**: (ourRef 값, 예: OUR-2025-001)
                📋 **진행 사항**: (summary 내용)
                📅 **처리 일시**: (현재 일시)
                🛡️ **상태**: 시스템 등록 완료
                ---
                ⏰ **후속 안내**: (IP 유형에 따른 다음 행정 기한 안내)

                요청하신 업무가 시스템에 정상적으로 반영되었습니다.
                ```

                ### 도구가 "파일 등록 가능 시간이 만료" 또는 토큰 오류를 반환한 경우:

                ```markdown
                ### 🚫 [업무 등록 실패]
                ---
                📂 **대상**: (사건 번호)
                📋 **사유**: 파일 등록 가능 시간이 만료되었거나 토큰이 유효하지 않아 업무 등록에 실패했습니다.
                ---
                ⏰ **후속 안내**: 새로 파일을 업로드하신 후 다시 시도해 주세요.
                파일 토큰은 발급 후 일정 시간이 지나면 만료될 수 있습니다.
                ```

                ### 도구가 다른 오류를 반환한 경우:

                ```markdown
                ### 🚫 [업무 등록 실패]
                ---
                📋 **사유**: (도구가 반환한 오류 메시지를 그대로 표시)
                ---
                시스템 오류가 발생했습니다. 담당자에게 문의해 주세요.
                ```

                ---

                ## 7. 화면 이동 (Navigation)

                사용자가 사건 상세 화면으로 이동을 요청하면:
                1. `searchFrontRouteTool`로 경로를 조회한다.
                2. `navigateToPage`를 호출한다.

                ---

                ## 8. 도메인별 후속 기한 안내

                ### 특허·실용신안
                - 의견제출통지서 수신 → 수신일로부터 2개월 이내 의견서 제출
                - 등록결정 → 3개월 이내 등록료 납부
                - 거절결정 → 등본 수령 후 30일 이내 불복심판 청구

                ### 상표
                - 출원 접수 → 심사 기간 약 12~15개월
                - 의견제출통지서 수신 → 2개월 이내 의견서 제출
                - 등록결정 → 등록료 납부 후 지정상품 보호 시작
                - 갱신등록 → 10년마다 갱신 필요

                ### 디자인
                - 출원 접수 → 심사 약 5~8개월
                - 등록결정 → 20년 보호 시작

                ---

                ## 9. UI 출력 규칙

                - `systemSeq`, `fileToken`, `docSeq` 등 개발 식별자는 사용자에게 절대 노출하지 마십시오.
                - 등록 성공 후에는 반드시 IP 유형에 맞는 **다음 단계 행정 기한**을 함께 안내하십시오.
                - 사건 번호는 반드시 링크 형식으로 변환하십시오: `[40-2025-0219818](/TRADEMARK/issues/APPMST20260000515)`
                """;
    }
}
